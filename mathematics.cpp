#include <iostream>
using namespace std;
int main() {
  
    int a, b;    
    cout <<"a =  "<< endl;
    cin >> a;
    cout << "b = "<< endl;
    cin >> b;
    
    cout <<"a + b = "<< a+b <<endl;
    cout <<"a - b = "<< a-b <<endl;
    cout <<"a * b = "<< a*b <<endl;
    cout <<"a / b = "<<(float) a/b <<endl;
    

    return 0;
    
}